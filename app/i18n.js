export const SUPPORTED_LANGUAGES = [
  { code: "en", name: "English", nativeName: "English", flag: "🇬🇧" },
  { code: "de", name: "German", nativeName: "Deutsch", flag: "🇩🇪" },
  { code: "ru", name: "Russian", nativeName: "Русский", flag: "🇷🇺" },
  { code: "tr", name: "Turkish", nativeName: "Türkçe", flag: "🇹🇷" },
  { code: "ar", name: "Arabic", nativeName: "العربية", flag: "🇸🇦" },
  { code: "fr", name: "French", nativeName: "Français", flag: "🇫🇷" },
  { code: "es", name: "Spanish", nativeName: "Español", flag: "🇪🇸" },
  { code: "uk", name: "Ukrainian", nativeName: "Українська", flag: "🇺🇦" },
];

const SUPPORTED_CODES = SUPPORTED_LANGUAGES.map((l) => l.code);

const getDeviceLanguage = () => {
  try {
    // Use React Native built-in — no native module needed
    const { NativeModules, Platform } = require("react-native");
    let locale = "en";
    if (Platform.OS === "android") {
      locale = NativeModules.I18nManager?.localeIdentifier || "en";
    } else {
      locale =
        NativeModules.SettingsManager?.settings?.AppleLocale ||
        NativeModules.SettingsManager?.settings?.AppleLanguages?.[0] ||
        "en";
    }
    const code = locale.split(/[-_]/)[0].toLowerCase();
    return SUPPORTED_CODES.includes(code) ? code : "en";
  } catch (e) {}
  return "en";
};

export const loadSavedLanguage = async () => {
  try {
    await db.execAsync(`
      CREATE TABLE IF NOT EXISTS user_prefs (
        key TEXT PRIMARY KEY,
        value TEXT NOT NULL
      );
    `);
    const row = await db.getFirstAsync(
      `SELECT value FROM user_prefs WHERE key = 'appLanguage'`,
    );
    if (row && SUPPORTED_CODES.includes(row.value)) {
      return row.value;
    }
  } catch (e) {
    console.error("loadSavedLanguage error:", e);
  }
  return null;
};

export const saveLanguage = async (code) => {
  try {
    await db.runAsync(
      `INSERT OR REPLACE INTO user_prefs (key, value) VALUES ('appLanguage', ?)`,
      [code],
    );
  } catch (e) {
    console.error("saveLanguage error:", e);
  }
};

export const changeLanguage = async (code) => {
  await i18n.changeLanguage(code);
  await saveLanguage(code);
};

export const initI18n = async () => {
  const saved = await loadSavedLanguage();
  const device = getDeviceLanguage();
  const initial = saved || device;

  await i18n.use(initReactI18next).init({
    resources: {
      en: { translation: en },
      de: { translation: de },
      ru: { translation: ru },
      tr: { translation: tr },
      ar: { translation: ar },
      fr: { translation: fr },
      es: { translation: es },
      uk: { translation: uk },
    },
    lng: initial,
    fallbackLng: "en",
    interpolation: { escapeValue: false },
    compatibilityJSON: "v4",
    debug: false,
    initImmediate: false,
    silent: true,
  });

  return initial;
};

export default i18n;
